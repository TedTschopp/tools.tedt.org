export function localRow(m, layer, i) {
  return i >= 0 ? (m.local.tables[layer]?.rows[m.val(i, layer)] ?? null) : null;
}
export function localValue(m, spec, i) {
  if (spec.layer === "hex") {
    const n = m.val(i, spec.column);
    return n == null ? null : n / spec.divisor;
  }
  return localRow(m, spec.layer, i)?.[spec.index] ?? null;
}
export function localArea(m, id, i) {
  const spec = m.local.fields[id];
  if (!spec || i < 0) return "";
  if (spec.layer === "hex")
    return "Hex " + m.val(i, "col") + ", " + m.val(i, "row");
  const row = localRow(m, spec.layer, i);
  if (!row) return "Outside the mapped source geography";
  return (
    {
      bg: "Block group ",
      tract: "Tract ",
      health: "Tract ",
      zcta: "ZIP / ZCTA ",
      energyArea: "Reporting area ",
      work: "Workplace block group ",
    }[spec.layer] + row[0]
  );
}
