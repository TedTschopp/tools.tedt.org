const sharedArt = {
  'aslan-hierate': 'aslan', 'aslan-empire': 'aslan', 'vargr-extents': 'vargr', 'empire-human': 'human', cheval: 'human',
};

export function portraitFor(id) {
  if (!Object.hasOwn(portraits, id) && !Object.hasOwn(sharedArt, id)) return null;
  const about = portraits[id] ?? portraits[sharedArt[id]];
  return { ...about, asset: sharedArt[id] ?? id };
}
